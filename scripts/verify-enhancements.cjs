const { chromium } = require(process.env.FLOWBUDGET_PLAYWRIGHT || 'playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')

async function main() {
  const base = 'http://127.0.0.1:5179'
  const authResponse = await fetch('http://127.0.0.1:8019/api/auth/login', {method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({email:'omarsolanki46@gmail.com',password:'LocalVerify123!'})})
  const auth = await authResponse.json()
  await fetch('http://127.0.0.1:8019/api/account/appearance', {method:'PUT',headers:{'Content-Type':'application/json',Authorization:'Bearer '+auth.token},body:JSON.stringify({wallpaper_image:''})})
  const browser = await chromium.launch({ headless:true, channel:'msedge' })
  const page = await browser.newPage({ viewport:{width:1440,height:1000} })
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  try {
    await page.goto(base)
    await page.getByRole('textbox',{name:'Email',exact:true}).fill('omarsolanki46@gmail.com')
    await page.getByRole('textbox',{name:'Password',exact:true}).fill('LocalVerify123!')
    await page.getByRole('button',{name:'Sign in',exact:true}).click()
    await page.locator('.top-actions .add-button').waitFor()
    await page.locator('.top-actions .add-button').click()
    await page.locator('.modal button[type=submit], .modal .modal-actions .primary').click()
    await page.getByRole('alert').first().waitFor()
    const description = `Duplicate-click test ${Date.now()}`
    await page.getByLabel('Amount',{exact:true}).fill('1')
    await page.getByLabel('Description',{exact:true}).fill(description)
    await page.route('**/api/transactions', async route => {
      if(route.request().method() === 'POST') {
        const response = await route.fetch()
        await new Promise(resolve => setTimeout(resolve, 900))
        await route.fulfill({response})
      } else await route.continue()
    })
    await page.locator('.modal .modal-actions .primary').click()
    await page.locator('.request-progress').waitFor()
    await page.keyboard.press('Enter')
    await page.keyboard.press('Enter')
    await page.keyboard.press('Enter')
    await page.locator('.modal-backdrop').waitFor({state:'hidden'})
    const count = await page.evaluate(async description => {
      const response=await fetch('/api/transactions?search='+encodeURIComponent(description),{headers:{Authorization:'Bearer '+sessionStorage.getItem('flowbudget_token')}})
      return (await response.json()).length
    },description)
    assert.equal(count,1)
    await page.goto(base+'/#/settings')
    await page.getByLabel('Font',{exact:true}).selectOption('verdana')
    await page.getByLabel('Text colour',{exact:true}).selectOption('charcoal')
    await page.getByLabel('Mobile number (with country code)').fill('+96512345678')
    await page.locator('form').filter({has:page.getByLabel('Font',{exact:true})}).getByRole('button',{name:'Save preferences',exact:true}).click()
    await page.getByText('Settings saved',{exact:true}).waitFor()
    await page.reload()
    await page.getByLabel('Font',{exact:true}).waitFor()
    assert.equal(await page.getByLabel('Font',{exact:true}).inputValue(),'verdana')
    assert.equal(await page.getByLabel('Mobile number (with country code)').inputValue(),'+96512345678')
    const panel = page.locator('.resizable-panel').first()
    const box = await panel.boundingBox()
    const grip = await panel.locator('.panel-resize-handle').boundingBox()
    await page.mouse.move(grip.x+8,grip.y+8)
    await page.mouse.down()
    await page.mouse.move(grip.x+108,grip.y+88,{steps:6})
    await page.mouse.up()
    assert.ok((await panel.boundingBox()).width > box.width)
    await page.locator('.appearance-panel input[type=file]').setInputFiles('public/flowbudget-logo.png')
    await page.getByText('Wallpaper updated',{exact:true}).waitFor()
    assert.equal(await page.locator('body').evaluate(el => el.classList.contains('has-wallpaper')),true)
    assert.equal(await panel.evaluate(el => getComputedStyle(el).opacity),'1')
    fs.mkdirSync('.verification',{recursive:true})
    await page.screenshot({path:'.verification/enhancements-desktop.png',fullPage:true})
    await page.setViewportSize({width:390,height:844})
    await page.goto(base+'/#/wallets')
    await page.getByRole('heading',{name:'Your wallets'}).waitFor()
    assert.ok(await page.locator('.mobile-transaction-action').isVisible())
    assert.ok(await page.locator('.signout-button').isVisible())
    assert.ok(!(await page.locator('.top-actions .add-button').isVisible()))
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth+1))
    await page.screenshot({path:'.verification/enhancements-mobile.png',fullPage:true})
    await page.goto(base+'/#/bank-messages')
    await page.getByRole('button',{name:'Add message',exact:true}).click()
    await page.getByLabel('Transaction message').fill('Purchase KWD 1.000 at local shop '+Date.now())
    await page.getByRole('button',{name:'Add for review'}).click()
    await page.locator('.modal-backdrop').waitFor({state:'hidden'})
    await page.getByRole('button',{name:'Review expense'}).first().click()
    await page.getByLabel('Amount',{exact:true}).fill('1')
    await page.getByLabel('Description',{exact:true}).fill('Reviewed bank purchase')
    await page.getByRole('button',{name:'Record expense',exact:true}).click()
    await page.getByText('Expense recorded',{exact:true}).waitFor()
    assert.equal(errors.length,0,errors.join('\n'))
    console.log('PASS: missing-field feedback, duplicate submission, preferences persistence, resizing, mobile add/logout, message-to-expense review, no browser errors')
  } catch (error) {
    console.error('Browser errors:', errors)
    console.error((await page.locator('body').innerText()).slice(0,3000))
    await page.screenshot({path:'.verification/enhancements-error.png',fullPage:true})
    throw error
  } finally { await browser.close() }
}
main().catch(e => { console.error(e); process.exitCode=1 })
