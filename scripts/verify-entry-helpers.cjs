const {chromium,request}=require(process.env.FLOWBUDGET_PLAYWRIGHT || 'playwright')
const assert=require('node:assert/strict')
const fs=require('node:fs')
async function main(){
  const base=process.env.FLOWBUDGET_PREVIEW_URL || 'http://127.0.0.1:5173'
  assert(['localhost','127.0.0.1'].includes(new URL(base).hostname))
  const client=await request.newContext({baseURL:base})
  const response=await client.post('/api/auth/login',{data:{email:'omarsolanki46@gmail.com',password:'PreviewOnly-2026!'}})
  assert(response.ok()); const {token,user}=await response.json()
  const browser=await chromium.launch({channel:'msedge',headless:true})
  fs.mkdirSync('.verification',{recursive:true})
  try{for(const width of [320,390,1440])for(const theme of ['light','dark']){
    const context=await browser.newContext({viewport:{width,height:850},reducedMotion:'reduce'})
    await context.addInitScript(({token,user})=>{
      sessionStorage.setItem('flowbudget_token',token)
      localStorage.setItem(`budgetly:entry:v1:${user.id}:personal`,JSON.stringify({savedAt:Date.now(),entries:[{type:'expense',description:'Coffee',wallet_id:1,category_id:''}]}))
    },{token,user})
    const page=await context.newPage(); await page.goto(base+'/#/transactions')
    await page.getByRole('button',{name:'Add transaction',exact:true}).first().click()
    await page.evaluate(theme=>{document.documentElement.dataset.theme=theme;document.documentElement.style.setProperty('--text',theme==='dark'?'#e4e8e7':'#172c38')},theme)
    const input=page.getByLabel('Description',{exact:true}); await input.focus()
    await page.getByRole('button',{name:'Use description Coffee'}).waitFor()
    assert.equal(await page.locator('datalist').count(),0)
    await page.getByRole('button',{name:'Hide description suggestions'}).click()
    assert.equal(await page.locator('.description-suggestions').count(),0)
    await input.fill('C'); await input.blur(); await input.focus()
    await page.getByRole('button',{name:'Use description Coffee'}).click()
    assert.equal(await input.inputValue(),'Coffee')
    if(width<820){
      await page.evaluate(()=>{
        const viewport=new EventTarget();viewport.height=440;viewport.offsetTop=0
        Object.defineProperty(window,'visualViewport',{configurable:true,value:viewport})
      })
      await page.getByRole('button',{name:'Close dialog'}).click()
      await page.getByRole('dialog').waitFor({state:'hidden'})
      await page.getByRole('button',{name:'Add transaction',exact:true}).first().click()
      await page.waitForTimeout(400)
      await input.focus(); await page.evaluate(()=>window.visualViewport.dispatchEvent(new Event('resize')))
    }
    await page.waitForTimeout(400)
    const dialog=await page.getByRole('dialog').boundingBox(),footer=await page.locator('.modal-footer').boundingBox(),body=await page.locator('.modal-body').boundingBox()
    assert(Math.abs(dialog.width-footer.width)<3,`Footer spans dialog: ${JSON.stringify({dialog,footer,body})}`)
    assert(body.y+body.height<=footer.y+1,'Fields never overlap footer')
    const field=await input.boundingBox()
    if(width<820)assert(field.y>=body.y-1 && field.y+field.height<=footer.y+1,'Focused description remains above action bar')
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1))
    await page.screenshot({path:`.verification/entry-helpers-${width}-${theme}.png`})
    await page.getByRole('button',{name:'Close dialog'}).click()
    await page.goto(base+'/#/settings')
    await page.locator('summary').filter({hasText:'Personal preferences'}).click()
    await page.locator('summary').filter({hasText:'Transaction helpers'}).click()
    await page.getByLabel('Description suggestions',{exact:true}).uncheck()
    await page.getByLabel('Transaction templates',{exact:true}).uncheck()
    await page.getByLabel('Balance preview before saving',{exact:true}).uncheck()
    await page.goto(base+'/#/transactions')
    await page.getByRole('button',{name:'Add transaction',exact:true}).first().click()
    await input.fill('C'); await input.focus()
    assert.equal(await page.locator('.description-suggestions').count(),0)
    assert.equal(await page.getByText('Templates',{exact:true}).count(),0)
    await context.close()
  }}finally{await browser.close();await client.dispose()}
  console.log('Entry helpers: inline suggestions, dismissal, saved preferences, full-width non-overlapping footer, keyboard-height simulation and light/dark responsive layouts passed.')
}
main().catch(error=>{console.error(error);process.exitCode=1})
